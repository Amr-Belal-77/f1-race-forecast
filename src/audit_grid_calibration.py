"""Audit out-of-sample F1 race-win probability by starting-grid band.

Run from the F1 project root:
    python src/audit_grid_calibration.py

Requires the file generated by backtest_ensemble.py:
    data/processed/ensemble_backtest_driver_predictions.csv

All 2022-2025 predictions are out-of-sample (models trained on earlier years).
2026 is reported separately because it has already been used repeatedly for diagnostics.
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / "data" / "processed" / "ensemble_backtest_driver_predictions.csv"
OUTPUT = ROOT / "data" / "processed" / "grid_calibration_by_band.csv"

if not INPUT.exists():
    raise FileNotFoundError(
        f"Missing {INPUT}\nRun: python src\\backtest_ensemble.py"
    )

df = pd.read_csv(INPUT)
required = ["season", "round", "driver", "grid_position", "winner", "V1", "V2", "Blend_50_50"]
missing = [column for column in required if column not in df.columns]
if missing:
    raise ValueError(f"Missing columns in backtest file: {missing}")

race_keys = ["season", "round"]
if df.duplicated(race_keys + ["driver"]).any():
    raise ValueError("Duplicate driver within a race")
if not df.groupby(race_keys)["winner"].sum().eq(1).all():
    raise ValueError("Expected exactly one winner per historical race")
if df["grid_position"].isna().any() or (df["grid_position"] <= 0).any():
    raise ValueError("Expected positive adjusted grid positions from backtest")

models = ["V1", "V2", "Blend_50_50"]
for model in models:
    if not np.isfinite(df[model]).all() or (df[model] < 0).any():
        raise ValueError(f"Invalid probability for {model}")
    sums = df.groupby(race_keys)[model].sum()
    if not np.allclose(sums.to_numpy(), 1.0, atol=1e-5):
        raise ValueError(f"{model} probabilities do not sum to 1 within each race")

bands = ["P1", "P2", "P3", "P4-P6", "P7-P10", "P11-P13", "P14+"]
df["grid_band"] = pd.cut(
    df["grid_position"],
    bins=[0, 1, 2, 3, 6, 10, 13, np.inf],
    labels=bands,
    right=True,
)


def summarize(data, sample_name):
    """Compare expected winners (sum of predicted mass) with observed winners."""
    races = data[race_keys].drop_duplicates().shape[0]
    if races == 0:
        return pd.DataFrame()
    rows = []
    for model in models:
        for band in bands:
            subset = data.loc[data["grid_band"] == band]
            expected_wins = float(subset[model].sum())
            actual_wins = int(subset["winner"].sum())
            rows.append({
                "sample": sample_name,
                "model": model,
                "grid_band": band,
                "races": races,
                "starts": len(subset),
                "expected_wins": expected_wins,
                "actual_wins": actual_wins,
                "predicted_win_share_pct": 100 * expected_wins / races,
                "actual_win_share_pct": 100 * actual_wins / races,
                "gap_percentage_points": 100 * (expected_wins - actual_wins) / races,
            })
    return pd.DataFrame(rows)

# Older walk-forward periods form the primary model-behavior check.
primary = df[df["season"].between(2022, 2025)].copy()
recent = df[df["season"] == 2026].copy()

if primary.empty:
    raise ValueError("No 2022-2025 out-of-sample predictions found")

results = [summarize(primary, "2022-2025")]
if not recent.empty:
    results.append(summarize(recent, "2026_diagnostic"))
summary = pd.concat(results, ignore_index=True)
OUTPUT.parent.mkdir(parents=True, exist_ok=True)
summary.to_csv(OUTPUT, index=False)

for period in summary["sample"].unique():
    print("\n" + "=" * 76)
    print(f"OUT-OF-SAMPLE GRID CALIBRATION: {period}")
    print("Expected wins = sum of all driver probabilities in the band")
    print("Positive gap = model assigned MORE probability than observed")
    print("=" * 76)
    for model in models:
        t = summary[(summary["sample"] == period) & (summary["model"] == model)]
        print(f"\n{model}")
        display = t[[
            "grid_band", "starts", "expected_wins", "actual_wins",
            "predicted_win_share_pct", "actual_win_share_pct", "gap_percentage_points"
        ]]
        print(display.to_string(index=False, formatters={
            "expected_wins": "{:.2f}".format,
            "predicted_win_share_pct": "{:.2f}%".format,
            "actual_win_share_pct": "{:.2f}%".format,
            "gap_percentage_points": "{:+.2f} pp".format,
        }))

print("\nBACK-OF-GRID (P14+) HIGH-CONFIDENCE HISTORICAL PREDICTIONS, 2022-2025")
back = primary[primary["grid_position"] >= 14].sort_values("Blend_50_50", ascending=False)
print(back[["season", "round", "driver", "grid_position", "winner", "Blend_50_50"]].head(12).to_string(index=False, formatters={"Blend_50_50": "{:.2%}".format}))

print("\nSaved audit to:", OUTPUT)
print("Note: small samples and special circumstances can produce large differences.")
